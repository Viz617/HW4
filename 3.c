#include <stdio.h>

int main(void)
{
    /*Префиксный инкремент прибавляет 1 и вернет новое значение, когда постфиксный сначало вернет
    старое значение и потом уже новое.
    Порядок в данном решении не важен, т.к k увеличивается после вывода*/
    int N;
    unsigned long long one = 1;
    int k = 1;
    scanf("%d",&N);
    while (k <= N){
        printf("%llu ",one);
        one = one * 16;
        k++;
    }
    return 0;
}